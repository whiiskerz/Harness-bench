const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
let currentBrowser;
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-webgl','--ignore-gpu-blocklist']});
 currentBrowser=browser;
 const page=await browser.newPage({viewport:{width:1490,height:940},acceptDownloads:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 page.on('console',e=>{if(e.type()==='error')console.log('BROWSER:',e.text())});
 await page.goto('http://127.0.0.1:8765/index.html',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>!!window.WFDT,{timeout:25000});
 const first=await page.evaluate(()=>({assemblyCount:WFDT.candidates().length,src:S.wires.length,model:WFDT.candidates().find(p=>p.partId===161)}));
 assert.ok(first.assemblyCount>=6,'Deutsch types including custom DT8 breakouts should be recognized');
 assert.equal(first.src,94);
 assert.equal(first.model.count,6);
 assert.ok(first.model.cavities.some(c=>c.a.connected));
 assert.ok(first.model.cavities.some(c=>c.a.connected&&c.b.state==='planned'),'mated side starts as unconfirmed plan');
 await page.locator('#tabs [data-tab="dt"]').click();
 assert.ok(await page.locator('#t-dt').isVisible());
 assert.ok(await page.locator('.dt-part').count()>=6);
 assert.equal(await page.locator('.dt-pro-kpis > div').count(),5);
 const part=page.locator('[data-dta="select"][data-id="161"]');
 await part.click();
 assert.match(await page.locator('.dt-inspector-head h3').textContent(),/TRUNK CONNECTOR/i);
 assert.equal(await page.locator('.dt-table tbody tr').count(),6);
 const ctl=(i,key)=>page.locator('[data-dt-index="'+i+'"][data-dt-field="'+key+'"]');
 const inputs=page.locator('.dt-assembly-halves');
 const sideA=page.locator('[data-dt-key="aHousing"]'),sideB=page.locator('[data-dt-key="bHousing"]');
 assert.equal(await sideA.inputValue(),'','No physical part number should be fabricated');
 await ctl(0,'state').selectOption('owner-confirmed');
 assert.equal(await page.evaluate(()=>S.dtAssemblies?.[161]?.cavities?.[0]?.state||'planned'),'planned','Cannot self-certify an empty mating-half record');
 await sideA.fill('DT04-6P');await sideA.blur();
 await sideB.fill('DT06-6S');await sideB.blur();
 await ctl(0,'destination').fill('Leash dual relay board A-');await ctl(0,'destination').blur();
 await ctl(0,'contactPart').fill('1062-16-0122');await ctl(0,'contactPart').blur();
 await ctl(0,'evidence').fill('Owner test photo #W-100; visually inspected');await ctl(0,'evidence').blur();
 await ctl(0,'state').selectOption('owner-confirmed');
 const record=await page.evaluate(()=>({r:S.dtAssemblies[161],p:WFDT.candidates().find(q=>q.partId===161)}));
 assert.equal(record.r.cavities[0].state,'owner-confirmed');
 assert.equal(record.p.cavities[0].b.contactPart,'1062-16-0122');
 assert.equal(record.p.sideA,'receptacle');assert.equal(record.p.sideB,'plug');
 assert.equal(WFDT.findings().some(f=>f.partId===161&&f.severity==='error'),false,'matching housing PNs are compatible');
 // Wrong role must be flagged by Validation Lab.
 await sideB.fill('DT04-6P');await sideB.blur();
 assert.ok(await page.evaluate(()=>WFDT.findings().some(q=>q.partId===161&&q.severity==='error'&&q.message.includes('same type'))));
 await page.locator('#tabs [data-tab="lab"]').click();
 assert.match(await page.locator('#wfLabRows').textContent(),/Mating halves/i);
 await page.locator('#tabs [data-tab="dt"]').click();
 await page.locator('[data-dta="select"][data-id="161"]').click();
 await sideB.fill('DT06-6S');await sideB.blur();
 const [csv]=await Promise.all([page.waitForEvent('download',{timeout:20000}),page.locator('[data-dta="export"]').first().click()]);
 assert.match(csv.suggestedFilename(),/two-sided-termination-matrix\.csv$/);
 const csvText=fs.readFileSync(await csv.path(),'utf8');
 assert.ok(csvText.includes('Leash dual relay board A-')&&csvText.includes('owner-confirmed'));
 await page.locator('#wfQuickSave').click();
 await page.reload({waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>!!window.WFDT);
 assert.equal(await page.evaluate(()=>S.dtAssemblies[161].cavities[0].state),'owner-confirmed');
 await page.locator('#tabs [data-tab="dt"]').click();
 await page.locator('[data-dta="select"][data-id="161"]').click();
 await page.screenshot({path:'wireforge-v025-dt-assembly-desktop.png',fullPage:true});
 // Browser layout in phone-sized viewport; table intentionally scrolls horizontally.
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'wireforge-v025-dt-assembly-mobile.png',fullPage:true});
 assert.equal(await page.locator('.dt-table-scroll').isVisible(),true);
 const overflow=await page.evaluate(()=>({body:document.body.scrollWidth,viewport:document.documentElement.clientWidth,table:document.querySelector('.dt-table-scroll').scrollWidth}));
 assert.ok(overflow.body<=overflow.viewport+85,'Table must scroll inside workspace, not expand entire mobile body: '+JSON.stringify(overflow));
 await page.setViewportSize({width:1400,height:940});
 await page.locator('[data-dta="render3d"]').first().click();
 await page.waitForURL('**/render3d.html',{timeout:22000});
 await page.waitForFunction(()=>document.querySelector('#loading')?.hidden===true || document.querySelector('#loadingTitle')?.textContent?.includes('Could not render'),null,{timeout:70000});
 assert.equal(await page.locator('#loading').isHidden(),true,'3D renderer did not load: '+errors.join(' | '));
 const before=await page.evaluate(()=>({m:window.__WF3D_MATES,stats:window.__WF3D_STATS,audit:window.__WF3D_MATE_EXIT_AUDIT}));
 assert.ok(before.m?.length>=6,'Every Deutsch body has an opposite mating half');
 assert.ok(before.m.some(x=>String(x.id)==='161'&&x.exits.length===6),'DT6 has six indexed mate-side exits');
 assert.ok(before.stats.paintedMateLeads>5,'Mating wire tails are rendered on other side');
 assert.ok(before.audit.every(a=>a.startError<1e-5),'Mate wire tails begin at their real assigned rear cavity ports');
 for(const a of before.m){const coords=a.exits.map(x=>x.p.map(n=>n.toFixed(5)).join(','));assert.equal(new Set(coords).size,coords.length,'No two mate cavities overlap for '+a.id)}
 await page.locator('[data-hardware-focus="deutsch"]').click();
 assert.equal(await page.locator('#editAssembly').isDisabled(),false,'Selected Deutsch hardware opens mating editor');
 assert.match(await page.locator('#matingStatus').textContent(),/HALF A/);
 await page.locator('#mateGap').evaluate(el=>{el.value='90';el.dispatchEvent(new Event('change',{bubbles:true}))});
 const opened=await page.evaluate(()=>window.__WF3D_MATES.find(x=>String(x.id)==='161').exits[0].p);
 await page.locator('#mateGap').evaluate(el=>{el.value='0';el.dispatchEvent(new Event('change',{bubbles:true}))});
 const closed=await page.evaluate(()=>window.__WF3D_MATES.find(x=>String(x.id)==='161').exits[0].p);
 assert.ok(Math.hypot(...opened.map((x,i)=>x-closed[i]))>.5,'Exploded view should separate the physical mate');
 await page.locator('#showMates').uncheck();
 assert.equal(await page.evaluate(()=>window.__WF3D_MATES.length),0,'Hide mates removes companion geometry');
 await page.locator('#showMates').check();
 assert.ok(await page.evaluate(()=>window.__WF3D_MATES.length)>0,'Show mates restores geometry');
 await page.screenshot({path:'wireforge-v025-3d-complete-mates.png',fullPage:true});
 if(errors.length)throw Error('Browser JavaScript exceptions: '+errors.join(' / '));
 console.log('PASS',JSON.stringify({assemblies:first.assemblyCount,mateLeads:before.stats.paintedMateLeads,fullMatedGeometry:true,persistentRecord:true,validation:true,mobile:overflow}));
 await browser.close();
})().catch(async err=>{console.error(err);try{await currentBrowser?.close()}catch{}process.exitCode=1});

import assert from 'node:assert/strict';
import {deutschFamily,housingPartNumber,parseHousing,makePair,auditPair,pairSummary,familySpec} from '../wireforge-dt-model.mjs';
const dt={id:1,type:'dt6',name:'Cabin DT6',pins:Array.from({length:6},(_,i)=>({number:String(i+1)}))};
assert.equal(deutschFamily(dt),'DT');
assert.equal(deutschFamily({type:'e90analog8',name:'DT8_ANALOG_SUB'}),'DT');
assert.equal(deutschFamily({type:'e90can8',name:'DT8_CAN_CONTROL'}),'DT');
assert.equal(deutschFamily({type:'e90dt12',name:'DT12_POWER_BREAKOUT'}),'DT');
assert.equal(deutschFamily({type:'mxrace',name:'ECU'}),null);
assert.equal(housingPartNumber('DT',6,'plug'),'DT06-6S');
assert.equal(housingPartNumber('DT',6,'receptacle'),'DT04-6P');
assert.equal(housingPartNumber('DT',8,'plug','A'),'DT06-08SA');
assert.equal(housingPartNumber('DT',12,'receptacle','B'),'DT04-12PB');
assert.deepEqual(parseHousing('DT04-6P'),{family:'DT',role:'receptacle',count:6,contact:'P',key:null});
assert.deepEqual(parseHousing('DT06-08SA'),{family:'DT',role:'plug',count:8,contact:'S',key:'A'});
assert.equal(familySpec('DTP').contacts,12);
assert.equal(familySpec('DTM').contacts,20);
const wires=[{id:7,sig:'GPO2 pump trigger',color:'GRN',awg:20,a:{p:1,i:0},b:{p:3,i:1}}];
let pair=makePair(dt,wires,{});
assert.equal(pair.count,6);
assert.equal(pair.sideA,'receptacle');
assert.equal(pair.sideB,'plug');
assert.equal(pair.cavities[0].a.connected,true);
assert.equal(pair.cavities[0].b.state,'planned');
assert.equal(pair.cavities[0].b.color,'GRN');
assert.equal(pair.cavities[1].b.state,'unassigned');
assert.equal(pairSummary(pair).confirmedB,0);
assert.ok(auditPair(pair).some(x=>x.message.includes('no terminations')||x.message.includes('planning lead')));
const matching={aHousing:'DT04-6P',bHousing:'DT06-6S',cavities:{0:{state:'owner-confirmed',color:'GRN',awg:20,contactPart:'1062-16-0122',destination:'Pump relay input',evidence:'Photo label #123'}}};
pair=makePair(dt,wires,matching);
assert.equal(pairSummary(pair).confirmedB,1);
assert.equal(auditPair(pair).filter(x=>x.severity==='error').length,0);
assert.equal(pairSummary(pair).completeRecord,true);
const broken=makePair(dt,wires,{...matching,bHousing:'DT04-6P'});
assert.ok(auditPair(broken).some(x=>x.severity==='error'&&x.message.includes('same type')));
const oversized=makePair(dt,wires,{...matching,cavities:{0:{...matching.cavities[0],awg:10}}});
assert.ok(auditPair(oversized).some(x=>x.severity==='error'&&x.message.includes('10 AWG')));
const keyPart={...dt,type:'dt12',pins:Array.from({length:12},(_,i)=>({number:String(i+1)}))};
const keyBad=makePair(keyPart,[],{aHousing:'DT04-12PA',bHousing:'DT06-12SB'});
assert.ok(auditPair(keyBad).some(x=>x.message.includes('keys differ')));
console.log('PASS two-sided Deutsch housing and termination data rules');
